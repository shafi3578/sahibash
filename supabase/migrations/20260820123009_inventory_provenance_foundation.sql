update public.listings
set
  source_type = coalesce(source_type, 'native'::public.listing_source_type),
  ownership_status = coalesce(ownership_status, 'claimed'::public.listing_ownership_status),
  freshness_status = case
    when status = 'sold' then 'sold_confirmed'::public.listing_freshness_status
    when status = 'expired' then 'expired'::public.listing_freshness_status
    else coalesce(freshness_status, 'seller_confirmed'::public.listing_freshness_status)
  end,
  publication_status = case
    when status = 'approved' then 'published'::public.listing_publication_status
    when status = 'pending' then 'pending_review'::public.listing_publication_status
    when status = 'rejected' then 'hidden'::public.listing_publication_status
    when status in ('sold', 'expired') then 'archived'::public.listing_publication_status
    else coalesce(publication_status, 'pending_review'::public.listing_publication_status)
  end,
  provenance_status = coalesce(provenance_status, 'trusted'::public.listing_provenance_status),
  source_first_seen_at = coalesce(source_first_seen_at, created_at),
  source_last_seen_at = coalesce(source_last_seen_at, updated_at),
  permission_basis = coalesce(permission_basis, 'direct_user_submission'),
  source_consent_at = coalesce(source_consent_at, created_at),
  provenance_confidence = coalesce(provenance_confidence, 1),
  noindex_external = case when source_type in ('native', 'migrated_legacy') then false else true end;

