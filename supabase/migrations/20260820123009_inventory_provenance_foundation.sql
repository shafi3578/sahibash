create or replace function public.set_listing_bridge_publication_fields()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if new.status = 'approved' then
    new.publication_status := 'published'::public.listing_publication_status;
  elsif new.status = 'pending' then
    new.publication_status := 'pending_review'::public.listing_publication_status;
  elsif new.status = 'rejected' then
    new.publication_status := 'hidden'::public.listing_publication_status;
  elsif new.status in ('sold', 'expired') then
    new.publication_status := 'archived'::public.listing_publication_status;
  end if;

  if new.status = 'sold' then
    new.freshness_status := 'sold_confirmed'::public.listing_freshness_status;
  elsif new.status = 'expired' then
    new.freshness_status := 'expired'::public.listing_freshness_status;
  end if;

  if new.source_type <> 'native'::public.listing_source_type then
    new.noindex_external := coalesce(new.noindex_external, true);
  end if;

  return new;
end;
$$;

drop trigger if exists trg_set_listing_bridge_publication_fields on public.listings;
create trigger trg_set_listing_bridge_publication_fields
before insert or update of status, source_type on public.listings
for each row execute function public.set_listing_bridge_publication_fields();

create or replace function public.mask_afghanistan_phone(phone text)
returns text
language sql
immutable
set search_path = ''
as $$
  select case
    when phone is null or length(regexp_replace(phone, '\D', '', 'g')) < 7 then null
    else left(regexp_replace(phone, '\D', '', 'g'), 4) || repeat('•', greatest(length(regexp_replace(phone, '\D', '', 'g')) - 6, 2)) || right(regexp_replace(phone, '\D', '', 'g'), 2)
  end;
$$;

