  coalesce(rc.report_count, 0) as report_count,
  case
    when coalesce(rc.report_count, 0) >= 3 or coalesce(l.publication_status::text, 'published') in ('removed','archived') then 'restricted'::public.trust_quality_band
    when coalesce(l.provenance_confidence, 0.5) < 0.35 or coalesce(l.freshness_status::text, 'fresh') in ('stale','expired') then 'needs_review'::public.trust_quality_band
    when coalesce(l.source_type::text, 'native') in ('native','dealer_managed','partner_feed','seller_approved_import')
      and coalesce(l.ownership_status::text, 'claimed') <> 'unclaimed'
      and coalesce(l.provenance_confidence, 0.5) >= 0.75
      then 'higher_confidence'::public.trust_quality_band
    else 'standard'::public.trust_quality_band
  end as quality_band,
  case
    when coalesce(l.source_type::text, 'native') = 'external_indexed' and coalesce(l.ownership_status::text, 'claimed') = 'unclaimed'
      then 'External seller; availability and ownership are less certain.'
    when coalesce(l.ownership_status::text, 'claimed') <> 'unclaimed'
      then 'Seller owns or manages this listing in Sahibash.'
    else 'Standard marketplace listing; use normal safety checks.'
  end as buyer_label_guidance,
  greatest(
    0,
    least(
      1,
      (coalesce(l.provenance_confidence, 0.5) * 0.45)
      + (case when coalesce(l.ownership_status::text, 'claimed') <> 'unclaimed' then 0.20 else 0 end)
      + (case when coalesce(l.source_type::text, 'native') in ('native','dealer_managed','partner_feed','seller_approved_import') then 0.15 else 0 end)
      + (case when coalesce(l.freshness_status::text, 'fresh') in ('fresh','seller_confirmed') then 0.15 else 0 end)
      - (coalesce(rc.report_count, 0) * 0.08)
    )
  )::numeric(5,4) as internal_quality_score
from public.listings l
left join report_counts rc on rc.listing_id = l.id;

create or replace view public.admin_source_health
with (security_invoker = true)
as
select
  coalesce(l.source_type::text, 'native') as source_type,
  coalesce(l.source_type::text, 'native') as source_name,
  count(*)::integer as total_listings,
  count(*) filter (where l.status = 'approved')::integer as approved_listings,
  count(*) filter (where coalesce(l.publication_status::text, 'published') in ('removed','archived'))::integer as removed_or_archived,
  count(*) filter (where coalesce(l.freshness_status::text, 'fresh') in ('stale','expired'))::integer as stale_or_expired,
  count(*) filter (where coalesce(l.ownership_status::text, 'claimed') <> 'unclaimed')::integer as claimed_or_native,
  round(coalesce(count(*) filter (where coalesce(l.ownership_status::text, 'claimed') <> 'unclaimed')::numeric / nullif(count(*), 0), 0), 4) as claim_or_native_share,
  round(coalesce(count(*) filter (where coalesce(l.freshness_status::text, 'fresh') in ('stale','expired'))::numeric / nullif(count(*), 0), 0), 4) as stale_rate
from public.listings l
group by coalesce(l.source_type::text, 'native')
having count(*) >= 3;

