-- 10) Add admin-only policies
do $$
begin
  if not exists (
    select 1 from pg_policies
    where schemaname = 'public' and tablename = 'admin_roles' and policyname = 'admin_roles_admin_only'
  ) then
    create policy "admin_roles_admin_only"
    on public.admin_roles
    for all
    using (public.is_admin(auth.uid()))
    with check (public.is_admin(auth.uid()));
  end if;

  if not exists (
    select 1 from pg_policies
    where schemaname = 'public' and tablename = 'admin_permissions' and policyname = 'admin_permissions_admin_only'
  ) then
    create policy "admin_permissions_admin_only"
    on public.admin_permissions
    for all
    using (public.is_admin(auth.uid()))
    with check (public.is_admin(auth.uid()));
  end if;

  if not exists (
    select 1 from pg_policies
    where schemaname = 'public' and tablename = 'admin_role_permissions' and policyname = 'admin_role_permissions_admin_only'
  ) then
    create policy "admin_role_permissions_admin_only"
    on public.admin_role_permissions
    for all
    using (public.is_admin(auth.uid()))
    with check (public.is_admin(auth.uid()));
  end if;

  if not exists (
    select 1 from pg_policies
    where schemaname = 'public' and tablename = 'admin_user_roles' and policyname = 'admin_user_roles_admin_only'
  ) then
    create policy "admin_user_roles_admin_only"
    on public.admin_user_roles
    for all
    using (public.is_admin(auth.uid()))
    with check (public.is_admin(auth.uid()));
  end if;

  if not exists (
    select 1 from pg_policies
    where schemaname = 'public' and tablename = 'audit_logs' and policyname = 'audit_logs_admin_only'
  ) then
    create policy "audit_logs_admin_only"
    on public.audit_logs
    for select
    using (public.is_admin(auth.uid()));
  end if;
end
$$;

