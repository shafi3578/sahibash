create table if not exists public.wanted_requests (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  locale public.language_code not null default 'fa',
  status public.wanted_request_status not null default 'active',
  urgency public.wanted_request_urgency not null default 'flexible',
  title text not null check (char_length(title) between 2 and 120),
  query_text text,
  category_id bigint references public.categories(id) on delete set null,
  category_node_id bigint references public.category_nodes(id) on delete set null,
  category_path text,
  province text,
  city text,
  district text,
  min_price numeric(14,2) check (min_price is null or min_price >= 0),
  max_price numeric(14,2) check (max_price is null or max_price >= 0),
  condition text,
  attributes jsonb not null default '{}'::jsonb,
  notification_channels text[] not null default array['in_app']::text[],
  notification_paused_at timestamptz,
  expires_at timestamptz not null default (now() + interval '90 days'),
  last_matched_at timestamptz,
  match_count int not null default 0 check (match_count >= 0),
  not_relevant_count int not null default 0 check (not_relevant_count >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint wanted_requests_price_order check (min_price is null or max_price is null or min_price <= max_price),
  constraint wanted_requests_channels_safe check (notification_channels <@ array['in_app','email','whatsapp']::text[])
);

