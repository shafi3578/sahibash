create or replace function public.record_demand_signal(
  p_signal_type text,
  p_locale text default null,
  p_query_text text default null,
  p_category_node_id bigint default null,
  p_category_path text default null,
  p_province text default null,
  p_district text default null,
  p_attributes jsonb default '{}'::jsonb,
  p_weight numeric default 1,
  p_source text default 'web'
)
returns bigint
language plpgsql
set search_path = ''
as $$
declare
  v_id bigint;
begin
  insert into public.demand_signals (
    signal_type, actor_user_id, locale, query_text, category_node_id, category_path,
    province, district, attributes, weight, source
  )
  values (
    p_signal_type,
    (select auth.uid()),
    case when p_locale in ('en','fa','ps') then p_locale::public.language_code else null end,
    nullif(left(coalesce(p_query_text, ''), 300), ''),
    p_category_node_id,
    nullif(left(coalesce(p_category_path, ''), 300), ''),
    nullif(left(coalesce(p_province, ''), 80), ''),
    nullif(left(coalesce(p_district, ''), 120), ''),
    coalesce(p_attributes, '{}'::jsonb),
    least(greatest(coalesce(p_weight, 1), 0.1), 20),
    nullif(left(coalesce(p_source, 'web'), 80), '')
  )
  returning id into v_id;
  return v_id;
end;
$$;

revoke execute on function public.record_demand_signal(text,text,text,bigint,text,text,text,jsonb,numeric,text) from public;
grant execute on function public.record_demand_signal(text,text,text,bigint,text,text,text,jsonb,numeric,text) to anon, authenticated, service_role;

create or replace view public.admin_supply_gap_cells
with (security_invoker = true)
as
select
  coalesce(category_path, 'uncategorized') as category_path,
  province,
  district,
  count(*) filter (where signal_type = 'search') as raw_searches,
  count(*) filter (where signal_type = 'zero_result_search') as zero_result_searches,
  count(*) filter (where signal_type = 'wanted_request') as wanted_requests,
  count(*) filter (where signal_type = 'contact_action') as contact_actions,
  sum(weight) as qualified_demand_score,
  case
    when count(*) >= 5 then round((sum(weight) + count(*) filter (where signal_type in ('wanted_request','contact_action')) * 2)::numeric, 2)
    else null
  end as privacy_safe_gap_score,
  max(created_at) as last_signal_at
from public.demand_signals
where created_at >= now() - interval '30 days'
group by coalesce(category_path, 'uncategorized'), province, district;

grant select on public.admin_supply_gap_cells to authenticated;

