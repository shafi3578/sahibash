function keyFromPath(path?: string | null) {
  if (!path) return "";
  const parts = path.split("/").filter(Boolean);
  return parts[parts.length - 1] ?? "";
}

export function localizeCategoryName(input: {
  locale: AppLocale;
  fallbackName: string;
  slug?: string | null;
  path?: string | null;
}) {
  const key = (input.slug || keyFromPath(input.path) || "").toLowerCase();
  if (!key) return input.fallbackName;
  const primary = CATEGORY_LABELS[input.locale][key]?.name;
  if (primary) return primary;
  if (input.locale !== "en") {
    const launchLeaf = LAUNCH_LEAF_LABELS[input.locale][key];
    if (launchLeaf) return launchLeaf;
    if (/^other-[a-z0-9-]+-model$/.test(key)) {
      const brand = input.fallbackName.replace(/^Other\s+/i, "").replace(/\s+Model$/i, "");
      return input.locale === "fa" ? `سایر مدل‌های ${brand}` : `د ${brand} نور ماډلونه`;
    }
  }
  return input.fallbackName;
}

export function localizeCategorySubtitle(input: {
  locale: AppLocale;
  fallbackSubtitle?: string | null;
  slug?: string | null;
  path?: string | null;
}) {
  const key = (input.slug || keyFromPath(input.path) || "").toLowerCase();
  if (!key) return input.fallbackSubtitle ?? "";
  return CATEGORY_LABELS[input.locale][key]?.subtitle ?? input.fallbackSubtitle ?? "";
}
